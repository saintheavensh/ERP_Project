export type JournalReferenceType = "sale" | "purchase" | "expense" | "service" | "depreciation" | "commission" | "supplier_payment" | "adjustment" | "asset_purchase" | "manual";

export type AccountType = "ASSET" | "LIABILITY" | "EQUITY" | "REVENUE" | "EXPENSE";

export interface Account {
    id: string;
    code: string;
    name: string;
    typeId: AccountType;
    parentId?: string | null | undefined;
    description?: string | null | undefined;
    isActive: boolean;
    isSystem: boolean;
    balance: number;
    createdAt: Date;
    updatedAt?: Date | null | undefined;
}

export type JournalStatus = "draft" | "posted" | "voided";

export interface JournalEntry {
    id: string;
    date: Date;
    description: string;
    referenceType?: string | null | undefined;
    referenceId?: string | null | undefined;
    status: JournalStatus;
    totalDebit: number;
    totalCredit: number;
    isAutoGenerated: boolean;
    createdBy?: string | null | undefined;
    postedBy?: string | null | undefined;
    postedAt?: Date | null | undefined;
    voidedBy?: string | null | undefined;
    voidedAt?: Date | null | undefined;
    voidReason?: string | null | undefined;
    createdAt: Date;
    updatedAt?: Date | null | undefined;
    lines?: JournalLine[];
}

export interface JournalLine {
    id: string;
    journalId?: string;
    accountId: string;
    debit: number;
    credit: number;
    description?: string | null | undefined;
    accountName?: string | null | undefined;
    accountCode?: string | null | undefined;
}
